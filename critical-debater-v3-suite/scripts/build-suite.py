#!/usr/bin/env python3
"""Generate the v3 skill suite from its core spec.

Follows the v2 ``build-skill-adapters.py`` pattern: ``core/skill-core.md`` is
the single semantic source; SKILL.md and the platform adapters are generated
from it. Shared debate-methodology assets (capability docs, data contracts,
the deterministic report renderer) are copied from the v2 suite so there is
exactly one source of truth for them.

Usage:
    python scripts/build-suite.py           # generate / refresh
    python scripts/build-suite.py --check   # fail if out-of-date
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

SUITE_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = SUITE_ROOT.parent
V2_SUITE = REPO_ROOT / "critical-debater-suite"
CORE_PATH = SUITE_ROOT / "core" / "skill-core.md"

GENERATION_NOTE = "> Generated by `scripts/build-suite.py`. Do not hand-edit this file."

BASE_FRONTMATTER = """---
name: critical-debater-v3-suite
description: >
  LangGraph-orchestrated multi-agent adversarial debate system (v3): multi-model
  provider access (DeepSeek/Kimi/GLM/Qwen/OpenAI/Anthropic/local), Chinese source
  adaptation, deterministic evidence-credibility scoring, eight-dimension quality
  assessment, and a React Web UI with live WebSocket progress. Use this skill when
  the user says \"debate\", \"start a debate\", \"red team this\", \"install the debate
  system\", or provides a topic for critical examination.
license: MIT-0
compatibility: {compatibility}
metadata:
  author: xwxga
  version: \"3.1.0\"
  homepage: \"https://github.com/yufish-gaga/critical-debater\"
  tags: debate, evidence, langgraph, multi-model, quality, report
---
"""

ROUTING_TABLE = """## Intent → Capability Routing

| User Intent | Route To |
|---|---|
| "install", "set up", "verify installation" | `scripts/check-install.sh` + core §Installation |
| "debate", "start a debate", "red team this" | core §Running a Debate (CLI / API / Web UI) |
| "resume a debate", "continue after crash" | core §Running a Debate → Resume |
| "cancel a debate" | core §Running a Debate → Cancel |
| "open the web ui", "monitor progress" | core §Running a Debate (Web UI) |
| "interpret results", "quality report" | `references/data-contracts.md` + core §Required Outputs |
| debate methodology (ingest / turns / judge / synthesis) | `capabilities/*.md` (auto-injected at runtime) |
"""

ADAPTER_TARGETS = """## Adapter Targets / 适配目标

- `adapters/claude-code/SKILL.md`
- `adapters/codex/SKILL.md`
- `adapters/openclaw/SKILL.md`

Top-level `SKILL.md` and the adapters are generated from `core/skill-core.md`.
顶层 `SKILL.md` 与适配层均由 `core/skill-core.md` 生成。

"""


def render_header(title: str) -> str:
    return f"""# {title}

## Changelog / 变更日志

| 时间 / Time | 作者 / Author | 变更 / Change |
|---|---|---|
| 2026-08-30 | Claude | 初始生成：v3 技能库路由与适配层 / Initial generation: v3 suite routing + adapters |

{GENERATION_NOTE}

"""


def render_main_skill(core_text: str) -> str:
    compatibility = (
        "Requires Python >= 3.10 with pip; Node.js >= 18 for the Web UI build; "
        "model provider API keys via environment variables."
    )
    return (
        BASE_FRONTMATTER.format(compatibility=compatibility)
        + render_header("Critical Debater v3 Suite — Routing")
        + ROUTING_TABLE
        + "\n"
        + ADAPTER_TARGETS
        + "## Core Source / 核心来源\n\n"
        + "The following core spec is the single source of truth:\n"
        + "以下 Core 规范是唯一语义来源：\n\n"
        + core_text
    )


def render_adapter(target: str, compatibility: str, runtime_notes: str, core_text: str) -> str:
    return (
        BASE_FRONTMATTER.format(compatibility=compatibility)
        + render_header(f"Critical Debater v3 Suite — {target} Adapter")
        + "## Adapter Notes / 适配说明\n\n"
        + runtime_notes
        + "\n\n"
        + ROUTING_TABLE
        + "\n"
        + "## Core Source / 核心来源\n\n"
        + "The following core spec is the single source of truth:\n"
        + "以下 Core 规范是唯一语义来源：\n\n"
        + core_text
    )


def sync_text(path: Path, content: str, check_only: bool) -> bool:
    if check_only:
        if not path.exists():
            print(f"MISSING: {path}")
            return False
        if path.read_text(encoding="utf-8") != content:
            print(f"OUTDATED: {path}")
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"WROTE: {path}")
    return True


def sync_copy(src: Path, dst: Path, check_only: bool) -> bool:
    if not src.exists():
        print(f"MISSING SOURCE: {src}")
        return False
    if check_only:
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            print(f"OUTDATED: {dst}")
            return False
        return True
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)
    print(f"COPY: {dst}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate/check the v3 skill suite")
    parser.add_argument("--check", action="store_true", help="Fail if generated files are out-of-date")
    args = parser.parse_args()

    if not CORE_PATH.exists():
        print(f"ERROR: Missing core spec: {CORE_PATH}")
        return 2

    core_text = CORE_PATH.read_text(encoding="utf-8")
    ok = True

    outputs: dict[Path, str] = {
        SUITE_ROOT / "SKILL.md": render_main_skill(core_text),
        SUITE_ROOT / "adapters" / "claude-code" / "SKILL.md": render_adapter(
            "Claude Code",
            "Requires Claude Code runtime, Python >= 3.10 with pip; Node.js for the Web UI.",
            "- Suggested root: `.claude/skills/critical-debater-v3-suite`\n"
            "- Install the python package from the repo checkout (`pip install -e .`)\n"
            "- Point `CRITICAL_DEBATER_SUITE_DIR` at this suite when run outside the repo\n"
            "- Never write API keys into files; environment variables only",
            core_text,
        ),
        SUITE_ROOT / "adapters" / "codex" / "SKILL.md": render_adapter(
            "Codex",
            "Requires Codex runtime, Python >= 3.10 with pip; Node.js for the Web UI.",
            "- Suggested root: `$CODEX_HOME/skills/critical-debater-v3-suite`\n"
            "- Use workspace-safe paths only; web-started workspaces are root-confined\n"
            "- Respect `CRITICAL_DEBATER_API_TOKEN` when the server enables auth",
            core_text,
        ),
        SUITE_ROOT / "adapters" / "openclaw" / "SKILL.md": render_adapter(
            "OpenClaw",
            "Requires OpenClaw runtime, Python >= 3.10 with pip; Node.js for the Web UI.",
            "- Use configured skill root only\n"
            "- No `../` traversal outside configured root\n"
            "- Respect `CRITICAL_DEBATER_API_TOKEN` when the server enables auth",
            core_text,
        ),
    }
    for path, generated in outputs.items():
        ok &= sync_text(path, generated, args.check)

    # Shared methodology assets — copied from the v2 suite (single source).
    if not V2_SUITE.is_dir():
        print(f"ERROR: v2 suite not found for asset copy: {V2_SUITE}")
        return 2
    pairs: list[tuple[Path, Path]] = []
    for capability in sorted((V2_SUITE / "capabilities").glob("*.md")):
        pairs.append((capability, SUITE_ROOT / "capabilities" / capability.name))
    pairs.append((V2_SUITE / "references" / "data-contracts.md",
                  SUITE_ROOT / "references" / "data-contracts.md"))
    pairs.append((V2_SUITE / "scripts" / "render-debate-report-from-json.py",
                  SUITE_ROOT / "scripts" / "render-debate-report-from-json.py"))
    for src, dst in pairs:
        ok &= sync_copy(src, dst, args.check)

    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
